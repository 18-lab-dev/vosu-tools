#!/usr/bin/env bun
/**
 * Regenerates src/shader-glsl.ts, the WebGL2 backend's GLSL ES 3.00, from the
 * WGSL in src/shader.ts with naga (the Rust tool beside this script). Run
 * after every shader change: `bun run glsl` in packages/render-core (needs
 * cargo). test/glsl.test.ts fails while the two are out of step.
 */
import { createHash } from "node:crypto";
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { shader } from "../src/shader";

const here = import.meta.dir;
const run = spawnSync(
  "cargo",
  ["run", "--quiet", "--release", "--manifest-path", join(here, "Cargo.toml")],
  { input: shader, encoding: "utf8", maxBuffer: 1 << 24 },
);
if (run.status !== 0) {
  console.error(run.stderr);
  process.exit(1);
}
const stages = JSON.parse(run.stdout);
const source = `// Generated by glsl/generate.ts from the WGSL in shader.ts (naga 30.0.0). Do not edit.
/** SHA-256 of the WGSL this was generated from. */
export const wgslSha256 = ${JSON.stringify(createHash("sha256").update(shader).digest("hex"))};
/** GLSL ES 3.00 per entry point, with the GLSL names of WGSL's \`g\` and textures. */
export const glsl = ${JSON.stringify(stages, null, 2)} as const;
`;
writeFileSync(join(here, "../src/shader-glsl.ts"), source);
console.log("wrote src/shader-glsl.ts");
